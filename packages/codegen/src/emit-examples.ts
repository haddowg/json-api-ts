import type { ApiExamples } from '@haddowg/json-api-client'
import type { OpenApiDocument } from './openapi'
import { deriveProvenance, provenanceLines } from './provenance'
import { jsonLiteral } from './source'

/**
 * Emit the operation examples as a standalone generated artifact:
 *
 * ```ts
 * export const examples: ApiExamples = { <type>: { operations: { … }, actions: { … } }, … }
 * ```
 *
 * It sits beside the client rather than in it because the examples outweigh the rest of the
 * client several times over and only a few consumers, such as a tool describing each operation,
 * read them. The const is annotated rather than `as const`, so a large document costs the type
 * checker nothing beyond the assignability check.
 */
export function emitExamples(doc: OpenApiDocument, examples: ApiExamples): string {
  const header = [
    '/**',
    ' * AUTO-GENERATED by @haddowg/json-api-codegen — do not edit by hand.',
    ' * Worked examples of each operation, as the source OpenAPI document declares them.',
    ' *',
    ...provenanceLines(deriveProvenance(doc)),
    ' */',
  ].join('\n')
  return `${[
    header,
    "import type { ApiExamples } from '@haddowg/json-api-client'",
    `export const examples: ApiExamples = ${jsonLiteral(examples)}`,
  ].join('\n\n')}\n`
}
